#ifndef MCROCK_GAME_PACKET_ID_H
#define MCROCK_GAME_PACKET_ID_H

//Packet IDs are varuint32 on the wire, so 0x80 and above take two bytes | Paket ID'leri wire üzerinde varuint32, 0x80 ve üstü iki bayt yer kaplıyor

#define MC_PACKET_LOGIN 0x01
#define MC_PACKET_PLAY_STATUS 0x02
#define MC_PACKET_SERVER_TO_CLIENT_HANDSHAKE 0x03
#define MC_PACKET_CLIENT_TO_SERVER_HANDSHAKE 0x04
#define MC_PACKET_DISCONNECT 0x05
#define MC_PACKET_RESOURCE_PACKS_INFO 0x06
#define MC_PACKET_RESOURCE_PACK_STACK 0x07
#define MC_PACKET_RESOURCE_PACK_RESPONSE 0x08
#define MC_PACKET_START_GAME 0x0B
#define MC_PACKET_LEVEL_CHUNK 0x3A
#define MC_PACKET_REQUEST_CHUNK_RADIUS 0x45
#define MC_PACKET_CHUNK_RADIUS_UPDATE 0x46
#define MC_PACKET_SET_LOCAL_PLAYER_AS_INITIALIZED 0x71
#define MC_PACKET_NETWORK_CHUNK_PUBLISHER_UPDATE 0x79
#define MC_PACKET_BIOME_DEFINITION_LIST 0x7A
#define MC_PACKET_CLIENT_CACHE_STATUS 0x81
#define MC_PACKET_NETWORK_SETTINGS 0x8F
#define MC_PACKET_PLAYER_AUTH_INPUT 0x90
#define MC_PACKET_CREATIVE_CONTENT 0x91
#define MC_PACKET_ITEM_REGISTRY 0xA2
#define MC_PACKET_REQUEST_NETWORK_SETTINGS 0xC1
#define MC_PACKET_JIGSAW_STRUCTURE_DATA 0xD5
#define MC_PACKET_VOXEL_SHAPES 0xED

//PlayStatus field values, written as big-endian int32 | PlayStatus alan değerleri big-endian int32 olarak yazılıyor
#define MC_PLAY_STATUS_LOGIN_SUCCESS 0
#define MC_PLAY_STATUS_FAILED_CLIENT 1
#define MC_PLAY_STATUS_FAILED_SERVER 2
#define MC_PLAY_STATUS_PLAYER_SPAWN 3

#endif